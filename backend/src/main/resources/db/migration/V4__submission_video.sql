--
-- 사진처럼 자식 테이블을 두지 않고 submissions에 컬럼으로 붙인다.
-- "1개까지"라는 규칙이 스키마로 강제되고, 조회에 조인이 늘지 않는다.
-- 여러 개를 받아야 할 일이 생기면 그때 테이블로 분리한다.
--
-- s3 프리픽스는 사진과 같은 submissions/다. Phase 8에서 보관 기간이 정해져
-- 수명 주기 규칙을 걸 때 영상도 같은 규칙에 함께 들어가야 하기 때문이다.
--
-- 영상은 브라우저에서 압축할 방법이 없어 원본이 그대로 올라간다.
-- 100MB 상한은 애플리케이션에서 검사한다 (서버가 재생 길이를 잴 수 없어 용량으로만 막는다).

