package com.njwenglish.entity.enums;

/**
 * 성적 화면이 그 종류를 어떤 그래프로 그리는가. <b>서버가 정하고 화면은 따른다.</b>
 *
 * <p>화면에서 testType을 보고 분기하면 성적 목록(S-7·P-4)과 주간 레포트(P-6)가
 * 갈라진다 — 실제로 chart 불리언을 둔 이유가 그것이었다.
 *
 * <ul>
 *   <li>NONE — 단어·리뷰. 텍스트와 통과 배지만이다(2026-09-10 회의)
 *   <li>BAR — 실전 모의고사. 맞힌 개수 막대. <b>정답률이 아니다</b>
 *   <li>SPLIT_BAR — 클리닉. 주차마다 내부지문·외부지문 막대 둘
 * </ul>
 *
 * <p>꺾은선으로 되돌리지 마라. 값이 정답률이 아니라 개수가 됐고, 개수는 주마다 전체
 * 문항 수가 달라서 선으로 이으면 기울기가 거짓말을 한다.
 */
public enum ScoreChartKind {
    NONE, BAR, SPLIT_BAR
}
